const PAUSE_MS = 8000;              // one page every 8 seconds; faster trips Wowhead's rate limit
const STORE_KEY = 'agfNpcProgress';  // progress survives page reloads

function loadProgress() {
  try { return JSON.parse(localStorage.getItem(STORE_KEY)) || {}; } catch (e) { return {}; }
}

function saveProgress(p) {
  localStorage.setItem(STORE_KEY, JSON.stringify(p));
}

// Pulls the data array out of one `new Listview({ id: '<id>', ... data: [...] })` block.
function extractListview(html, id) {
  const marker = html.indexOf("id: '" + id + "'");
  if (marker < 0) return null;
  const re = /data:\s*\[/g;
  re.lastIndex = marker;
  const m = re.exec(html);
  const nextLv = html.indexOf('new Listview(', marker);
  if (!m || (nextLv > 0 && m.index > nextLv)) return null;
  const start = m.index + m[0].length - 1;
  let depth = 0, inStr = false, quote = '', esc = false;
  for (let j = start; j < html.length; j++) {
    const c = html[j];
    if (inStr) {
      if (esc) esc = false; else if (c === '\\') esc = true; else if (c === quote) inStr = false;
      continue;
    }
    if (c === '"' || c === "'") { inStr = true; quote = c; }
    else if (c === '[') depth++;
    else if (c === ']' && --depth === 0) return parseLiteral(html.slice(start, j + 1));
  }
  return null;
}

// Wowhead writes most listview data as JSON, but some pages use JavaScript object
// notation (unquoted keys). Try JSON first; otherwise evaluate the array literal, the same
// way the page itself does when it renders.
function parseLiteral(text) {
  try { return JSON.parse(text); } catch (e) { return Function('"use strict"; return (' + text + ');')(); }
}

async function readNpc(id) {
  const res = await fetch('/forever/npc=' + id);
  const html = await res.text();
  if (res.status !== 200 || /<title>Human Verification/.test(html)) return { blocked: true };
  const record = { displayID: Number((html.match(/displayId = (\d+)/) || [])[1] || 0), abilities: [] };
  try {
    record.abilities = (extractListview(html, 'abilities') || []).map(a => [a.id, a.name]);
  } catch (e) {
    record.error = String(e); // keep going; the build reports these
    console.warn(`Adventure Guide: couldn't read abilities for NPC ${id}: ${e}`);
  }
  return record;
}

async function whNpcs() {
  const progress = loadProgress();
  const todo = NPC_IDS.filter(id => !(id in progress));
  console.log(`Adventure Guide: ${NPC_IDS.length - todo.length} of ${NPC_IDS.length} done, ${todo.length} to go (about ${Math.ceil(todo.length * PAUSE_MS / 60000)} min).`);
  for (const id of todo) {
    const result = await readNpc(id);
    if (result.blocked) {
      console.warn('Adventure Guide: Wowhead asked for human verification. Reload the page, complete the check, then paste this script and run  await whNpcs()  again. Progress is saved.');
      return;
    }
    progress[id] = result;
    saveProgress(progress);
    const done = Object.keys(progress).length;
    if (done % 10 === 0) console.log(`Adventure Guide: ${done} of ${NPC_IDS.length}`);
    await new Promise(r => setTimeout(r, PAUSE_MS));
  }
  console.log('Adventure Guide: Done. Now run  copy(whNpcsResult())  and paste it into tools/wowhead/npcs.json');
}

function whNpcsResult() {
  return JSON.stringify({
    source: "https://www.wowhead.com/forever (NPC pages: 'abilities' listview and model display ID)",
    fetched: new Date().toISOString().slice(0, 10),
    format: { npcs: 'npcID -> { displayID, abilities: [[spellID, name], ...] }' },
    npcs: loadProgress(),
  }, null, 1);
}

function whNpcsReset() {
  localStorage.removeItem(STORE_KEY);
  console.log('Adventure Guide: progress cleared.');
}
