const PAUSE_MS = 12000;                // one page every 12 seconds; faster trips Wowhead's check
const STORE_KEY = 'agfItemProgress1';  // progress survives page reloads
// Listview fields that aren't about the item's power.
const DROP_FIELDS = new Set(['appearances', 'displayName', 'displayid', 'flags2', 'source', 'sourcemore',
  'envChange', 'modes', 'firstseenpatch', 'itemSquishEraId', 'popularity', 'sellprice', 'cooldown', 'dura']);

function loadProgress() {
  try { return JSON.parse(localStorage.getItem(STORE_KEY)) || { ranges: {}, items: {} }; }
  catch (e) { return { ranges: {}, items: {} }; }
}

function saveProgress(p) {
  localStorage.setItem(STORE_KEY, JSON.stringify(p));
}

// Index of the bracket that closes the one at `start`, skipping strings.
function matchBracket(text, start) {
  const open = text[start], close = open === '[' ? ']' : '}';
  let depth = 0, inStr = false, quote = '', esc = false;
  for (let j = start; j < text.length; j++) {
    const c = text[j];
    if (inStr) {
      if (esc) esc = false; else if (c === '\\') esc = true; else if (c === quote) inStr = false;
      continue;
    }
    if (c === '"' || c === "'") { inStr = true; quote = c; }
    else if (c === open) depth++;
    else if (c === close && --depth === 0) return j;
  }
  return -1;
}

// The page writes its items as a JavaScript literal (some keys unquoted), the same way
// the page itself evaluates it.
function parseLiteral(text) {
  try { return JSON.parse(text); } catch (e) { return Function('"use strict"; return (' + text + ');')(); }
}

async function readRange([lo, hi]) {
  // Wowhead item filter 151 is the item ID: >= lo and <= hi.
  const res = await fetch(`/forever/items?filter=151:151;2:4;${lo}:${hi}`);
  const html = await res.text();
  if (/<title>Human Verification/.test(html) || res.status === 403 || res.status === 429) return { blocked: true };
  const at = html.indexOf('listviewitems = [');
  if (at < 0) return { items: [] };
  const start = html.indexOf('[', at);
  const end = matchBracket(html, start);
  const list = end > 0 ? parseLiteral(html.slice(start, end + 1)) : [];
  const truncated = /_truncated: 1/.test(html);
  return { items: list, truncated };
}

async function whItems() {
  const p = loadProgress();
  const wanted = new Set(ITEM_IDS);
  const todo = ITEM_RANGES.filter(r => !(r.join('-') in p.ranges));
  console.log(`Adventure Guide: ${ITEM_RANGES.length - todo.length} of ${ITEM_RANGES.length} pages read, ${todo.length} to go (about ${Math.ceil(todo.length * PAUSE_MS / 60000)} min).`);
  for (const range of todo) {
    const result = await readRange(range);
    if (result.blocked) {
      console.warn('Adventure Guide: Wowhead asked for human verification. Reload the page, complete the check, then paste this script and run  await whItems()  again. Progress is saved.');
      return;
    }
    let kept = 0;
    for (const item of result.items) {
      if (!wanted.has(item.id)) continue;
      const rec = {};
      for (const [k, v] of Object.entries(item)) if (!DROP_FIELDS.has(k)) rec[k] = v;
      p.items[item.id] = rec;
      kept++;
    }
    p.ranges[range.join('-')] = { kept, truncated: !!result.truncated };
    saveProgress(p);
    if (result.truncated) console.warn(`Adventure Guide: range ${range.join('-')} hit the page limit; some items may be missing.`);
    await new Promise(r => setTimeout(r, PAUSE_MS));
  }
  const missing = ITEM_IDS.filter(id => !(id in p.items)).length;
  console.log(`Adventure Guide: Done. ${Object.keys(p.items).length} items read (${missing} not on Wowhead). Now run  copy(whItemsResult())  and paste it into tools/wowhead/items.json`);
}

function whItemsResult() {
  return JSON.stringify({
    source: "https://www.wowhead.com/forever item lists (filtered by item ID)",
    fetched: new Date().toISOString().slice(0, 10),
    format: { items: 'itemID -> Wowhead listview fields: level, reqlevel, classs, subclass, slot, armor, dps, speed, reqclass, and stat keys (str, agi, sta, int, spi, ...)' },
    items: loadProgress().items,
  }, null, 1);
}

function whItemsReset() {
  localStorage.removeItem(STORE_KEY);
  console.log('Adventure Guide: progress cleared.');
}
